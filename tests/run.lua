  local r = { consecration = true, hoj = true }
  eq(#Engine.decide(view(t, { now = 1, enemies = 1, ready = r, judgementRemains = 6 }), {}).side, 0)
  eq(Engine.decide(view(t, { now = 1, enemies = 3, ready = r, judgementRemains = 6 }), {}).side[1], "consecration")
