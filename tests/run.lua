-- Run with: luajit tests/run.lua   (from the repo root)
local ns = {}
for _, f in ipairs({ "Tracker", "Mana", "Engine" }) do
  assert(loadfile("Sigil/Core/" .. f .. ".lua"))("Sigil", ns)
end
local Tracker, Mana, Engine = ns.Tracker, ns.Mana, ns.Engine

local passed, failed = 0, 0
local function test(name, fn)
  local ok, err = pcall(fn)
  if ok then passed = passed + 1 else failed = failed + 1; print("FAIL " .. name .. "\n     " .. tostring(err)) end
end
local function eq(a, b, msg)
  if a ~= b then error((msg or "") .. " expected " .. tostring(b) .. ", got " .. tostring(a), 2) end
end

local ALL = { command = true, righteousness = true, wisdom = true, consecration = true, hoj = true }
local function view(t, extra)
  local v = t:snapshot(extra.now)
  v.combat, v.target, v.known = true, true, ALL
  for k, x in pairs(extra) do v[k] = x end
  return v
end

test("weave: full cycle with a 3.3 speed weapon", function()
  local t = Tracker.new()
  local S = {}
  eq(Engine.decide(view(t, { now = 0 }), S).main.id, "command")
  t:castSeal("command", 0)
  eq(Engine.decide(view(t, { now = 0.1 }), S).main.id, "attack")
  t:swing(1.0, 3.3); eq(t.stacks, 1)
  t:swing(4.3, 3.3); eq(t.stacks, 2)
  local d = Engine.decide(view(t, { now = 4.4 }), S)
  eq(d.main.id, "attack"); eq(d.next, "righteousness")
  t:swing(7.6, 3.3); eq(t.stacks, 3)
  d = Engine.decide(view(t, { now = 7.7 }), S)
  eq(d.main.id, "righteousness"); eq(d.main.urgent, true); eq(d.main.why, "Swap at 3 stacks. Your next swing releases them.")
  t:castSeal("righteousness", 8.0)
  d = Engine.decide(view(t, { now = 8.1 }), S)
  eq(d.main.id, "attack"); eq(d.main.why, "Your next swing releases the stacks.")
  local rel = t:swing(10.9, 3.3)
  eq(rel.seal, "command"); eq(rel.count, 3)
  eq(t.stored, "righteousness"); eq(t.stacks, 1)
  eq(Engine.decide(view(t, { now = 11.0 }), S).main.id, "command")
  t:castSeal("command", 11.2)
  rel = t:swing(14.2, 3.3)
  eq(rel.seal, "righteousness"); eq(rel.count, 1)
  eq(t.stored, "command"); eq(t.stacks, 1)
  eq(Engine.decide(view(t, { now = 14.3 }), S).main.id, "attack")
end)

test("swap that can't beat the next swing is called for after it", function()
  local t = Tracker.new()
  t:castSeal("command", 0)
  t:swing(1, 3.3); t:swing(4.3, 3.3); t:swing(7.6, 3.3)
  local v = view(t, { now = 10.5 })          -- next swing in 0.4s
  v.gcdRemains = 1.2                          -- but the global cooldown has 1.2s left
  local d = Engine.decide(v, {})
  eq(d.main.id, "righteousness"); eq(d.main.urgent, false); eq(d.main.why, "Swap right after this swing.")
  v = view(t, { now = 10.5 }); v.gcdRemains = 0.2
  eq(Engine.decide(v, {}).main.urgent, true)
end)

test("seal pair can be chosen", function()
  local t = Tracker.new()
  local known = { command = true, righteousness = true, light = true, wisdom = true }
  local S = { primary = "righteousness", secondary = "light" }
  eq(Engine.decide(view(t, { now = 0, known = known }), S).main.id, "righteousness")
  t:castSeal("righteousness", 0)
  t:swing(1, 3.3); t:swing(4.3, 3.3); t:swing(7.6, 3.3)
  eq(Engine.decide(view(t, { now = 7.7, known = known }), S).main.id, "light")
  local p, s2 = Engine.pair(known, { secondary = "none" })
  eq(p, "command"); eq(s2, nil)
  p, s2 = Engine.pair({ righteousness = true }, { primary = "command" })
  eq(p, "righteousness", "falls back when the chosen seal isn't known")
  -- Seal of Wisdom as the second seal is woven, not treated as mana recovery
  S = { secondary = "wisdom" }
  t = Tracker.new(); t:castSeal("command", 0)
  t:swing(1, 3.3); t:swing(4.3, 3.3); t:swing(7.6, 3.3)
  eq(Engine.decide(view(t, { now = 7.7, known = known }), S).main.id, "wisdom")
  t:castSeal("wisdom", 8); t:swing(10.9, 3.3)
  eq(Engine.decide(view(t, { now = 11, known = known }), { secondary = "wisdom", pattern = "burst" }).main.id, "command")
end)

test("crusader opener", function()
  local t = Tracker.new()
  local known = { command = true, righteousness = true, crusader = true }
  local S = { opener = "elite" }
  eq(Engine.decide(view(t, { now = 0, known = known }), S).main.id, "command", "not an elite: no opener")
  local d = Engine.decide(view(t, { now = 0, known = known, elite = true }), S)
  eq(d.main.id, "crusader")
  t:castSeal("crusader", 0)
  d = Engine.decide(view(t, { now = 1, known = known, elite = true }), S)
  eq(d.main.id, "attack"); eq(d.main.why, "Judgement marks the target.")
  d = Engine.decide(view(t, { now = 2, known = known, elite = true, crusaderDone = true }), S)
  eq(d.main.id, "command"); eq(d.main.why, "Target marked. On to your main seal.")
  eq(Engine.decide(view(Tracker.new(), { now = 0, known = known }), { opener = "always" }).main.id, "crusader")
  eq(Engine.decide(view(t, { now = 2, known = known, elite = true }), { opener = "off" }).main.id, "attack", "off: crusader is left alone")
end)

