  eq(#Engine.decide(view(t, { now = 1, ready = r, judgementRemains = 2 }), { stun = "solo" }).side, 0, "solo: automatic, no mark")
  eq(Engine.decide(view(t, { now = 1, ready = r, judgementRemains = 2, inGroup = true }), { stun = "solo" }).side[1], "hoj", "in a group: manual, mark shown")
  eq(#Engine.decide(view(t, { now = 1, ready = r, judgementRemains = 2, inGroup = true }), { stun = "always" }).side, 0)
